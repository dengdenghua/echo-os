import {
  expect,
  test as base,
  type Locator,
  type Page,
} from "@playwright/test";

type ExpectedApiFailure = {
  method: string;
  path: string;
  status: number;
  seen: number;
};

// A test that deliberately provokes an API failure (for example a wrong
// password) declares it here. The fixture then requires that exact failure to
// happen and still reports every other one.
const expectedApiFailures = new WeakMap<Page, ExpectedApiFailure[]>();

export function expectApiFailure(
  page: Page,
  failure: { method: string; path: string; status: number },
): void {
  const entries = expectedApiFailures.get(page) ?? [];
  entries.push({ ...failure, method: failure.method.toUpperCase(), seen: 0 });
  expectedApiFailures.set(page, entries);
}

function matchExpectedFailure(
  page: Page,
  path: string,
  status: number,
  method?: string,
): ExpectedApiFailure | undefined {
  return expectedApiFailures
    .get(page)
    ?.find(
      (entry) =>
        entry.path === path &&
        entry.status === status &&
        (method === undefined || entry.method === method.toUpperCase()),
    );
}

function apiPath(url: string): string | null {
  try {
    const parsed = new URL(url);
    return parsed.pathname.startsWith("/api/") ? parsed.pathname : null;
  } catch {
    return url.startsWith("/api/") ? url : null;
  }
}

function shouldIgnoreRequestFailure(errorText: string): boolean {
  return /net::ERR_ABORTED/i.test(errorText);
}

function shouldIgnoreConsoleError(text: string): boolean {
  // 404 (missing resource) and 403 (permission gated in e2e env) are
  // backend/data-setup issues, not frontend regressions.
  if (
    /Failed to load resource: the server responded with a status of 40[34]/i.test(
      text,
    )
  ) {
    return true;
  }
  return /ResizeObserver loop completed with undelivered notifications/i.test(
    text,
  );
}

// Prepare one workspace page across both supported E2E lanes:
// - developer UI lane: local auth is enabled, so log in and inject the token;
// - isolated full-stack lane: auth is disabled in config.e2e.yaml, so the
//   workspace is already accessible and no fabricated credential is needed.
async function prepareWorkspaceAuth(
  page: Page,
  username = "e2e-tester",
): Promise<void> {
  const authStatus = await page.request.get("/api/auth/status");
  if (!authStatus.ok()) {
    throw new Error(
      `auth status failed: ${authStatus.status()} ${await authStatus.text()}`,
    );
  }
  const status = (await authStatus.json()) as { enabled?: boolean };
  if (!status.enabled) return;

  const res = await page.request.post("/api/auth/local/login", {
    data: { username },
  });
  if (!res.ok()) {
    throw new Error(
      `local-auth login failed: ${res.status()} ${await res.text()}`,
    );
  }
  const data = (await res.json()) as {
    access_token: string;
    user: unknown;
  };
  if (!data.access_token) {
    throw new Error("local-auth login returned no access_token");
  }
  await injectAuthIntoPage(page, data.access_token, data.user);
}

// Inject the auth token into localStorage so the SPA accepts the session.
// Keys must match frontend/src/core/auth/api.ts.
async function injectAuthIntoPage(page: Page, token: string, user: unknown) {
  await page.addInitScript(
    ({ token, user, ts }) => {
      window.localStorage.setItem("echo_auth_token", token);
      window.localStorage.setItem("echo_user", JSON.stringify(user));
      window.localStorage.setItem("echo_auth_ts", String(ts));
    },
    { token, user, ts: Date.now() },
  );
}

/** The test owner password generated by playwright.full.config.ts. */
export function ownerPassword(): string {
  const password = process.env.ECHO_E2E_OWNER_PASSWORD;
  if (!password) {
    throw new Error(
      "ECHO_E2E_OWNER_PASSWORD is not set; run through playwright.full.config.ts",
    );
  }
  return password;
}

export function desktop(page: Page): Locator {
  return page.getByRole("main", { name: "ECHO OS 桌面" });
}

export function dock(page: Page): Locator {
  return page.getByRole("navigation", { name: "程序坞" });
}

export function lockScreenPassword(page: Page): Locator {
  return page.getByRole("textbox", { name: "密码" });
}

/** Sign in through the appliance lock screen as the device owner. */
export async function signIn(page: Page, path = "/"): Promise<void> {
  await page.goto(path);
  // The first page load also waits for Vite's cold dependency compile.
  await expect(lockScreenPassword(page)).toBeVisible({ timeout: 60_000 });
  await expect(page.getByRole("textbox", { name: "用户名" })).toHaveValue(
    "admin",
  );
  await lockScreenPassword(page).fill(ownerPassword());
  await page.getByRole("button", { name: "进入桌面" }).click();
  await expect(dock(page)).toBeVisible({ timeout: 30_000 });
  await expect(lockScreenPassword(page)).toHaveCount(0);
}

/** Open an app from the Launchpad (应用库) and return its desktop window. */
export async function openFromLaunchpad(
  page: Page,
  appName: string,
): Promise<Locator> {
  await dock(page).getByRole("button", { name: "应用库", exact: true }).click();
  const search = page.getByRole("textbox", { name: "搜索应用" });
  await expect(search).toBeVisible();
  await search.fill(appName);
  // The Launchpad grid is the only place the search narrows; the menu bar may
  // already show a focused app with the same name.
  await page
    .locator(".mac-launchpad")
    .getByRole("button", { name: appName, exact: true })
    .click();
  await expect(search).toHaveCount(0);
  return page.getByRole("dialog", { name: appName, exact: true });
}

export async function openWorkbench(page: Page): Promise<Locator> {
  const workbench = await openFromLaunchpad(page, "工作台");
  await expect(workbench).toBeVisible();
  await expect(workbench.getByTestId("chat-composer-input")).toBeVisible({
    timeout: 30_000,
  });
  return workbench;
}

export const test = base.extend<{ desktopPage: Page; authedPage: Page }>({
  page: async ({ page }, run) => {
    const issues: string[] = [];

    page.on("pageerror", (error) => {
      issues.push(`pageerror: ${error.message}`);
    });

    page.on("console", (message) => {
      if (message.type() !== "error") {
        return;
      }
      const text = message.text();
      if (shouldIgnoreConsoleError(text)) {
        return;
      }
      const failedStatus = /status of (\d{3})/.exec(text)?.[1];
      const failedPath = apiPath(message.location().url || "");
      if (
        failedStatus &&
        failedPath &&
        matchExpectedFailure(page, failedPath, Number(failedStatus))
      ) {
        return;
      }
      const location = message.location();
      const where = location.url
        ? `${location.url}:${location.lineNumber}:${location.columnNumber}`
        : "unknown location";
      issues.push(`console error at ${where}: ${text}`);
    });

    page.on("requestfailed", (request) => {
      const path = apiPath(request.url());
      if (!path) {
        return;
      }
      const errorText = request.failure()?.errorText || "unknown failure";
      if (shouldIgnoreRequestFailure(errorText)) {
        return;
      }
      issues.push(`API request failed ${path}: ${errorText}`);
    });

    page.on("response", (response) => {
      const status = response.status();
      const path = apiPath(response.url());
      if (!path) {
        return;
      }
      const expected = matchExpectedFailure(
        page,
        path,
        status,
        response.request().method(),
      );
      if (expected) {
        expected.seen += 1;
        return;
      }
      if (status < 500) {
        return;
      }
      issues.push(`API ${status} response ${path}`);
    });

    await run(page);
    await page.waitForTimeout(100);
    for (const expected of expectedApiFailures.get(page) ?? []) {
      if (expected.seen === 0) {
        issues.push(
          `expected API failure did not happen: ${expected.method} ${expected.path} ${expected.status}`,
        );
      }
    }
    expect(issues, issues.join("\n")).toEqual([]);
  },

  // Page signed in to the appliance desktop through the lock screen.
  desktopPage: async ({ page }, run) => {
    await signIn(page);
    await run(page);
  },

  // Authenticated page: logs in via local-auth then injects the token so
  // workspace routes are accessible instead of redirecting to /login. It is
  // also safe in the isolated full-stack config where auth is disabled.
  authedPage: async ({ page }, run) => {
    await prepareWorkspaceAuth(page);
    await run(page);
  },
});

export { expect };
